export function getDeptInfo(deptCode) {
  if (!deptCode) return null;
  const clean = String(deptCode).trim();
  const padded = clean.length === 1 ? `0${clean}` : clean;
  const match = DEPARTEMENTS_MAP[padded] || DEPARTEMENTS_MAP[clean];
  if (match) {
    return { nom: match.nom, zone: match.region, region: match.region };
  }
  return { nom: `Département ${clean}`, zone: 'France', region: 'France' };
}

export function getDeptCodeFromPostal(cp) {
  if (!cp) return '';
  const s = String(cp).trim();
  if (s.startsWith('20')) {
    const n = parseInt(s, 10);
    return n < 20200 ? '2A' : '2B';
  }
  return s.slice(0, 2);
}
